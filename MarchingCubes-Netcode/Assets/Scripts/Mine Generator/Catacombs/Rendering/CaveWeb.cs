using UnityEngine;

namespace MineGenerator.Catacombs
{
    /// <summary>
    /// Одна паутина: объём, в котором игрок вязнет, и то, что рвётся выстрелом.
    ///
    /// Логику замедления держит не она, а тот, кто двигает игрока: торможение должно
    /// входить в расчёт скорости, а не толкать персонажа со стороны. Здесь только числа
    /// и метка, по которой движение узнаёт паутину среди прочих коллайдеров.
    ///
    /// Читается опросом каждый кадр, а НЕ через OnTriggerEnter/Exit, и это важно
    /// по двум причинам.
    ///
    /// Первая: паутина живёт ровно до следующей генерации уровня, и CaveWebs.Clear сносит
    /// её вместе с коллайдером. События выхода игрок бы не дождался никогда — остался бы
    /// замедленным навсегда, посреди пустого коридора, без единой зацепки почему.
    /// То же самое при разрыве выстрелом. Опрос состояния такого класса ошибок
    /// не допускает в принципе.
    ///
    /// Вторая: опрашивает тот, кого замедляют, поэтому вязнет ровно он. Пауки, когда
    /// появятся, сквозь свою же паутину пройдут свободно — если решим иначе, менять
    /// придётся их движение, а не этот компонент.
    /// </summary>
    public sealed class CaveWeb : MonoBehaviour
    {
        [Tooltip("Во сколько раз медленнее игрок идёт внутри паутины.")]
        [SerializeField, Range(0.05f, 1f)] private float speedScale = 0.25f;

        /// <summary>
        /// Во сколько раз медленнее игрок падает внутри паутины.
        ///
        /// Отдельно от горизонтальной скорости, потому что паутина натянута поперёк хода:
        /// входят в неё горизонтально, но вязнуть надо и при падении сквозь — иначе
        /// затянутая щель между этажами остаётся обычной дырой.
        /// </summary>
        [Tooltip("Во сколько раз медленнее игрок падает внутри паутины.")]
        [SerializeField, Range(0.05f, 1f)] private float fallScale = 0.2f;

        public float SpeedScale => speedScale;
        public float FallScale => fallScale;

        public void Configure(float speed, float fall)
        {
            speedScale = speed;
            fallScale = fall;
        }

        /// <summary>
        /// Рвёт паутину. Зовётся попаданием — взрывом гранаты, киркой, чем угодно.
        ///
        /// Сносит объект целиком вместе с триггером, поэтому замедление пропадает тем же
        /// кадром: опрос со стороны игрока просто перестаёт её находить.
        /// </summary>
        public void Tear()
        {
            if (Application.isPlaying) Destroy(gameObject);
            else DestroyImmediate(gameObject);
        }
    }
}
