using System;
using Unity.Mathematics;
using UnityEngine;

namespace MineGenerator.Catacombs
{
    /// <summary>
    /// Кривая сложности стадии: рост плюс синус по опорным точкам.
    ///
    /// Форма заказана пользователем: «лёгкая — сложная — средняя — сложная, по синусу
    /// плюс кривая». И она же совпадает с тем, что разборы Megabonk находят в его
    /// десятиминутной стадии: база давления растёт всё время, а поверх неё два пика —
    /// рои на 4:00 и 7:00, — с передышкой между ними и подготовкой к боссу после
    /// второго. Опорные точки по умолчанию и есть эти 0.4 и 0.7 стадии.
    ///
    /// Почему синус не обычный, с постоянным периодом. У ровного синуса гребни
    /// расставлены через равные промежутки, а у Megabonk (и у заказанной формы) — нет:
    /// до первого гребня долгий разгон, между гребнями короткая передышка, после
    /// второго длинный спад. Поэтому фаза синуса идёт кусочно-линейно по опорным
    /// точкам: 0 в начале, 1 на первом гребне, 2 в провале, 3 на втором гребне,
    /// 4 в конце. У <c>-cos(pi * фаза)</c> производная в целых точках фазы нулевая,
    /// так что на стыках кусков излома нет: волна гладкая при любой расстановке гребней.
    ///
    /// Рост умножает волну, а не складывается с ней. Иначе провал в середине
    /// оказался бы не «средним», а таким же лёгким, как старт, — а смысл формы
    /// именно в том, что каждое затишье тяжелее предыдущего.
    /// </summary>
    [Serializable]
    public sealed class RunCurve
    {
        [Tooltip("Во сколько раз база давления вырастает к концу стадии.")]
        [Range(1f, 5f)] public float trendPeak = 2.2f;

        [Tooltip("Изгиб роста. Больше единицы — медленный старт и крутой конец.")]
        [Range(0.5f, 3f)] public float trendPower = 1.6f;

        [Tooltip("Размах волны: гребень выше базы и провал ниже неё во столько раз.")]
        [Range(0f, 0.9f)] public float waveAmplitude = 0.35f;

        [Tooltip("Первый гребень, доля стадии. У Megabonk первый рой — 4:00 из 10.")]
        [Range(0.05f, 0.9f)] public float firstPeak = 0.4f;

        [Tooltip("Передышка между гребнями, доля стадии.")]
        [Range(0.1f, 0.95f)] public float lull = 0.55f;

        [Tooltip("Второй гребень, доля стадии. У Megabonk второй рой — 7:00 из 10.")]
        [Range(0.15f, 0.97f)] public float secondPeak = 0.7f;

        /// <summary>Рост базы: 1 в начале, <see cref="trendPeak"/> в конце стадии.</summary>
        public float Trend(float t) => 1f + (trendPeak - 1f) * math.pow(math.saturate(t), trendPower);

        /// <summary>
        /// Фаза волны: 0 старт, 1 первый гребень, 2 передышка, 3 второй гребень, 4 конец.
        /// Опорные точки упорядочиваются здесь же — перепутанные в инспекторе,
        /// они давали бы фазу, идущую вспять.
        /// </summary>
        public float Phase(float t)
        {
            t = math.saturate(t);

            var a = math.clamp(firstPeak, 0.01f, 0.97f);
            var b = math.clamp(lull, a + 0.01f, 0.98f);
            var c = math.clamp(secondPeak, b + 0.01f, 0.99f);

            if (t < a) return t / a;
            if (t < b) return 1f + (t - a) / (b - a);
            if (t < c) return 2f + (t - b) / (c - b);

            return 3f + (t - c) / (1f - c);
        }

        /// <summary>Волна: -1 в затишье, +1 на гребне.</summary>
        public float Wave(float t) => -math.cos(math.PI * Phase(t));

        /// <summary>Сколько давления сейчас относительно базы в начале стадии.</summary>
        public float Intensity(float t) => Trend(t) * (1f + waveAmplitude * Wave(t));

        /// <summary>Как назвать этот кусок стадии для интерфейса.</summary>
        public string Section(float t)
        {
            var wave = Wave(t);

            if (wave > 0.6f) return "НАКАТ";
            if (wave < -0.6f) return t < firstPeak ? "затишье" : t < secondPeak ? "передышка" : "перед бурей";

            // Растёт волна или спадает — по тому, в какой половине куска стоит фаза.
            return (int)math.floor(Phase(t)) % 2 == 0 ? "нарастает" : "спадает";
        }
    }
}
