using UnityEngine;

namespace MineGenerator.Catacombs
{
    /// <summary>
    /// Единицы боя.
    ///
    /// Живучесть особи раньше была целым числом попаданий: мелочь держала одно, тарантул
    /// четыре, граната била на три. Восемь пушек с уровнями, томами «+10% урона», критами
    /// и уроном со временем в целых попаданиях не выражаются — 3 × 1.1 это 3.3, а не 3,
    /// поэтому здоровье теперь дробное, в HP.
    ///
    /// Одно прежнее попадание — десять HP. Так все сегодняшние числа переходят умножением,
    /// и прогоны дают то же, что до перевода. Поля, которые живут в сохранённой сцене
    /// и в ассетах видов (<see cref="SpiderKind.Health"/>, живучесть Матки, урон гранаты),
    /// по-прежнему задаются в попаданиях и переводятся в HP кодом: смени им единицы —
    /// и сохранённые значения молча поменяли бы смысл (грабли №8).
    /// </summary>
    public static class CombatUnits
    {
        /// <summary>Сколько HP в одном попадании прежней модели.</summary>
        public const float HitPoints = 10f;

        /// <summary>Попадания прежней модели → HP.</summary>
        public static float Hits(float hits) => hits * HitPoints;
    }

    /// <summary>
    /// Кто нанёс урон. По нему считаются убийства пушки (задания, статистика, баланс)
    /// и, позже, урон по игроку. Новые пушки дописываются в конец: номер пишется
    /// в метки джобов и в сохранения статистики.
    /// </summary>
    public enum DamageSource : ushort
    {
        Unknown = 0,

        /// <summary>Отладка стенда и прогонов: клавиша B, «игрок» прогона.</summary>
        Debug = 1,

        GrenadeLauncher = 2,

        Queen = 3,

        /// <summary>Мир: паника, отлив и прочее, что убивает не оружием.</summary>
        Environment = 4,

        Count
    }

    /// <summary>
    /// Убийство особи толпы — для опыта, валюты, заданий и статистики.
    /// Пишется толпой сразу после джоба, который убил, и раздаётся пачкой раз в кадр
    /// (<see cref="SpiderCrowd.Killed"/>): на двести убитых одним взрывом это один вызов,
    /// а не двести.
    /// </summary>
    public struct KillRecord
    {
        /// <summary>Где особь была в момент смерти, в мировых координатах.</summary>
        public Vector3 Position;

        /// <summary>Номер вида в толпе (<see cref="SpiderCrowd.KindAt"/>).</summary>
        public int Kind;

        /// <summary>Сколько попаданий держит вид — по нему считается ценность ихора.</summary>
        public int KindHealth;

        public bool Elite;

        /// <summary>Разорвана на куски, а не убита целой.</summary>
        public bool Gibbed;

        public DamageSource Source;
    }
}
